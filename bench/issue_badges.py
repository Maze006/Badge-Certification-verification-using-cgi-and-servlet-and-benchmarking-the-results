"""
Issues a badge for every completed module, by calling the real
issuance endpoint.

This is not a database fixture: it drives IssueServlet over HTTP
exactly the way the wallet page does, so the badges the benchmark then
verifies were minted by the actual issuance code path, with real
verification codes generated by BadgeCode.java.

    python bench/issue_badges.py            issue everything outstanding
    python bench/issue_badges.py --limit 20 issue only the first 20

Requires Tomcat to be running (scripts/start_tomcat.bat).
"""

import argparse
import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

SERVLET_BASE = "http://localhost:8080/badgeportal"


def post(url, fields):
    data = urllib.parse.urlencode(fields).encode("utf-8")
    req = urllib.request.Request(url, data=data, method="POST")
    req.add_header("Content-Type", "application/x-www-form-urlencoded")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.status, json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as err:
        body = err.read().decode("utf-8", "replace")
        try:
            return err.code, json.loads(body)
        except ValueError:
            return err.code, {"status": "HTTP_" + str(err.code), "message": body[:200]}


def completions(limit=None):
    """Reads the completion list straight from MySQL."""
    sys.path.insert(0, "cgi")
    import dbconfig                                   # noqa: E402
    import mysql.connector                            # noqa: E402

    conn = mysql.connector.connect(**dbconfig.db_params())
    cur = conn.cursor()
    cur.execute(
        "SELECT c.student_id, c.module_id "
        "FROM module_completions c "
        "WHERE NOT EXISTS (SELECT 1 FROM badges b "
        "                  WHERE b.student_id = c.student_id "
        "                    AND b.module_id  = c.module_id) "
        "ORDER BY c.student_id, c.module_id"
        + (" LIMIT %d" % limit if limit else "")
    )
    rows = cur.fetchall()
    cur.close()
    conn.close()
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--limit", type=int, default=None,
                    help="issue at most this many badges")
    ap.add_argument("--base", default=SERVLET_BASE,
                    help="servlet base URL (default %s)" % SERVLET_BASE)
    args = ap.parse_args()

    try:
        with urllib.request.urlopen(args.base + "/api/health", timeout=10) as r:
            health = json.loads(r.read().decode("utf-8"))
    except Exception as exc:                          # noqa: BLE001
        print("Cannot reach the servlet at %s -- is Tomcat running?" % args.base)
        print("  (%s)" % exc)
        print("  start it with: scripts\\start_tomcat.bat")
        return 1

    if health.get("status") != "UP":
        print("Servlet is reachable but reports status=%s" % health.get("status"))
        return 1

    pending = completions(args.limit)
    if not pending:
        print("Nothing to do: every completed module already has a badge.")
        return 0

    print("Issuing %d badge(s) via POST %s/api/issue" % (len(pending), args.base))
    print()

    counts = {}
    started = time.perf_counter()
    first_codes = []

    for i, (student_id, module_id) in enumerate(pending, start=1):
        status, body = post(args.base + "/api/issue",
                            {"studentId": student_id, "moduleId": module_id})
        state = body.get("status", "HTTP_%s" % status)
        counts[state] = counts.get(state, 0) + 1

        if state == "ISSUED" and len(first_codes) < 5:
            first_codes.append((body["student"]["name"],
                                body["module"]["title"],
                                body["tier"],
                                body["verificationCode"]))

        if i % 25 == 0 or i == len(pending):
            print("  %4d / %d" % (i, len(pending)))

    elapsed = time.perf_counter() - started

    print()
    print("Done in %.1fs" % elapsed)
    for state in sorted(counts):
        print("  %-16s %d" % (state, counts[state]))

    if first_codes:
        print()
        print("Sample of the codes just minted:")
        for name, title, tier, code in first_codes:
            print("  %-20s %-30s %-6s %s" % (name[:20], title[:30], tier, code))

    return 0


if __name__ == "__main__":
    sys.exit(main())
