package com.badgeportal;

import javax.servlet.http.HttpServlet;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.SQLIntegrityConstraintViolationException;
import java.sql.Timestamp;

/**
 * Approving or rejecting a badge claim.
 *
 *     POST /admin/review
 *
 * This is where a claim becomes a credential. Nothing before this point
 * has a verification code: a student can submit whatever they like, and
 * it stays inert until an administrator looks at the evidence and says
 * yes. That ordering is the whole reason the codes mean anything.
 *
 * APPROVAL USES THE SAME ISSUANCE PATH AS A MODULE BADGE
 *
 * The code is generated by BadgeCode.generate() with the same secret and
 * the same payload shape IssueServlet uses. A claim badge is therefore
 * indistinguishable from a module badge at verification time -- same
 * format, same tamper check, same JSON -- and cgi/verify.py verifies it
 * without knowing claims exist. Inventing a second code scheme here
 * would have split the verification story in two and broken the
 * benchmark's parity check.
 *
 * POST only, with a CSRF token. Approving a badge is exactly the kind of
 * state change that must not be reachable by following a link.
 */
public class ReviewServlet extends HttpServlet {

    private static final long serialVersionUID = 1L;

    private static final String SQL_INSERT_BADGE =
        "INSERT INTO badges (student_id, module_id, claim_id, source, "
      + "                    verification_code, tier, score, "
      + "                    issued_at_ms, issued_at) "
      + "VALUES (?, NULL, ?, 'ADMIN_APPROVED', ?, ?, ?, ?, ?)";

    private static final String SQL_MARK =
        "UPDATE badge_claims SET status = ?, reviewed_by = ?, "
      + "       reviewed_at = ?, review_note = ? "
      + "WHERE claim_id = ? AND status = 'PENDING'";

    /**
     * A claim carries no score -- there is no marked assessment behind
     * it. The tier the admin confirms is the real signal, so the score
     * column records the bottom of that tier's band rather than
     * inventing a precise-looking number nobody measured.
     */
    private static double scoreForTier(String tier) {
        if ("GOLD".equals(tier))   return 90.0;
        if ("SILVER".equals(tier)) return 75.0;
        return 60.0;
    }

    @Override
    protected void doPost(HttpServletRequest req, HttpServletResponse resp)
            throws IOException {

        Accounts.Account admin = Auth.current(req);
        String ctx = req.getContextPath();
        String back = ctx + "/admin/dashboard";

        if (!Auth.csrfValid(req)) {
            resp.sendRedirect(back + "?error=" + enc(
                "Your session expired. Please sign in again and retry."));
            return;
        }

        int claimId;
        try {
            claimId = Integer.parseInt(req.getParameter("claimId").trim());
        } catch (Exception e) {
            resp.sendRedirect(back + "?error=" + enc("No claim was selected."));
            return;
        }

        String action = req.getParameter("action");
        String note   = trim(req.getParameter("note"), 400);

        Claims.Claim claim;
        try {
            claim = Claims.byId(claimId);
        } catch (SQLException e) {
            log("[badgeportal] review lookup failed for claim " + claimId, e);
            resp.sendRedirect(back + "?error=" + enc("Could not read that claim."));
            return;
        }

        if (claim == null) {
            resp.sendRedirect(back + "?error=" + enc("That claim no longer exists."));
            return;
        }

        // Someone else may have reviewed it while this page sat open.
        // Re-deciding a settled claim would issue a second badge.
        if (!claim.isPending()) {
            resp.sendRedirect(back + "?error=" + enc(
                "That claim has already been " + claim.status.toLowerCase() + "."));
            return;
        }

        if ("reject".equals(action)) {
            if (note.isEmpty()) {
                resp.sendRedirect(back + "?error=" + enc(
                    "Give a reason when rejecting, so the student can act on it."));
                return;
            }
            try {
                if (mark(claimId, "REJECTED", admin.accountId, note)) {
                    resp.sendRedirect(back + "?done=" + enc("Claim rejected."));
                } else {
                    resp.sendRedirect(back + "?error=" + enc(
                        "That claim was reviewed by someone else first."));
                }
            } catch (SQLException e) {
                log("[badgeportal] reject failed for claim " + claimId, e);
                resp.sendRedirect(back + "?error=" + enc("Could not save that decision."));
            }
            return;
        }

        if (!"approve".equals(action)) {
            resp.sendRedirect(back + "?error=" + enc("Unrecognised action."));
            return;
        }

        // The admin may confirm the student's proposed tier or override it.
        String tier = tierOf(req.getParameter("tier"), claim.proposedTier);

        try {
            String code = issue(claim, tier);
            if (code == null) {
                resp.sendRedirect(back + "?error=" + enc(
                    "Could not allocate a verification code. Please retry."));
                return;
            }
            if (!mark(claimId, "APPROVED", admin.accountId,
                      note.isEmpty() ? null : note)) {
                // The badge exists but the claim was settled elsewhere
                // in the meantime. Say so rather than pretend.
                log("[badgeportal] badge " + code + " issued but claim "
                    + claimId + " was no longer pending");
            }
            resp.sendRedirect(back + "?done=" + enc("Badge issued: " + code));
        } catch (SQLException e) {
            log("[badgeportal] approval failed for claim " + claimId, e);
            resp.sendRedirect(back + "?error=" + enc(
                "Could not issue the badge. Please retry."));
        }
    }

    /** A GET here is somebody typing the URL. */
    @Override
    protected void doGet(HttpServletRequest req, HttpServletResponse resp)
            throws IOException {
        resp.sendRedirect(req.getContextPath() + "/admin/dashboard");
    }

    // -----------------------------------------------------------------
    /**
     * Mints the badge. Returns the code, or null if no unique code could
     * be allocated.
     */
    private String issue(Claims.Claim claim, String tier) throws SQLException {
        long issuedAtMs = System.currentTimeMillis();
        double score = scoreForTier(tier);

        Connection conn = null;
        try {
            conn = Db.borrow();

            // Twelve hex digits give ample room, but the unique index is
            // the real guarantee; nudging the timestamp yields a fresh
            // digest on the vanishingly rare collision.
            for (int attempt = 0; attempt < 5; attempt++) {
                String candidate = BadgeCode.generate(
                        BadgeCode.CLAIM_PREFIX, claim.studentId,
                        BadgeCode.NO_MODULE, issuedAtMs, Config.secret());

                PreparedStatement ps = conn.prepareStatement(SQL_INSERT_BADGE);
                try {
                    ps.setInt(1, claim.studentId);
                    ps.setInt(2, claim.claimId);
                    ps.setString(3, candidate);
                    ps.setString(4, tier);
                    ps.setDouble(5, score);
                    ps.setLong(6, issuedAtMs);
                    ps.setTimestamp(7, new Timestamp(issuedAtMs));
                    ps.executeUpdate();
                    return candidate;
                } catch (SQLIntegrityConstraintViolationException dup) {
                    issuedAtMs++;
                } finally {
                    ps.close();
                }
            }
            return null;
        } finally {
            Db.release(conn);
        }
    }

    /**
     * Settles the claim.
     *
     * The WHERE clause carries AND status = 'PENDING', so two admins
     * reviewing the same claim at the same moment cannot both succeed:
     * the second update matches no rows and returns false. Checking the
     * status in Java first would leave a window between the check and
     * the write.
     */
    private boolean mark(int claimId, String status, int reviewerId, String note)
            throws SQLException {
        Connection conn = null;
        try {
            conn = Db.borrow();
            PreparedStatement ps = conn.prepareStatement(SQL_MARK);
            try {
                ps.setString(1, status);
                ps.setInt(2, reviewerId);
                ps.setTimestamp(3, new Timestamp(System.currentTimeMillis()));
                if (note == null) ps.setNull(4, java.sql.Types.VARCHAR);
                else ps.setString(4, note);
                ps.setInt(5, claimId);
                return ps.executeUpdate() > 0;
            } finally {
                ps.close();
            }
        } finally {
            Db.release(conn);
        }
    }

    private static String tierOf(String raw, String fallback) {
        if ("GOLD".equalsIgnoreCase(raw))   return "GOLD";
        if ("SILVER".equalsIgnoreCase(raw)) return "SILVER";
        if ("BRONZE".equalsIgnoreCase(raw)) return "BRONZE";
        return (fallback == null) ? "BRONZE" : fallback;
    }

    private static String trim(String s, int max) {
        if (s == null) return "";
        s = s.trim();
        return s.length() > max ? s.substring(0, max) : s;
    }

    private static String enc(String s) {
        try {
            return java.net.URLEncoder.encode(s, "UTF-8");
        } catch (IOException e) {
            return "Action failed";
        }
    }
}
